#!/usr/bin/env node
// Writes docs/THIRD-PARTY-LICENSES.md (list + full licence texts) and public/licenses.txt
// (the same texts, served with every deploy): every package shipped in a production build,
// with its version, licence, source and licence file.
//   - PHP: composer.lock "packages" (what `composer install --no-dev` installs;
//     "packages-dev" is left out).
//   - JavaScript: package-lock.json packages that are not dev-only (what Vite can
//     bundle into public/build; build tools and @types/* are left out).
// Plain Node, no dependencies. Run from anywhere: `node scripts/licenses.mjs`
// (or `npm run licenses`) after any composer or npm dependency change.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (file) => JSON.parse(readFileSync(join(root, file), "utf8"));

const licenceText = (value) => {
  if (Array.isArray(value)) return value.length ? value.join(" OR ") : "UNKNOWN";
  if (value && typeof value === "object") return value.type ?? "UNKNOWN";
  return value || "UNKNOWN";
};

const cleanUrl = (url) =>
  (url || "")
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^ssh:\/\/git@/, "https://")
    .replace(/\.git$/, "");

const byNameThenVersion = (a, b) =>
  a.name.localeCompare(b.name, "en") || a.version.localeCompare(b.version, "en", { numeric: true });

// PHP
const composerLock = readJson("composer.lock");
const php = (composerLock.packages ?? []).map((p) => ({
  name: p.name,
  dir: `vendor/${p.name}`,
  version: String(p.version).replace(/^v(?=\d)/, ""),
  licence: licenceText(p.license),
  source: cleanUrl(p.source?.url || p.homepage || `https://packagist.org/packages/${p.name}`),
}));

// JavaScript
const npmLock = readJson("package-lock.json");
const seen = new Set();
const js = [];
for (const [path, p] of Object.entries(npmLock.packages ?? {})) {
  if (path === "" || p.dev === true || p.devOptional === true || p.link) continue;
  const name = p.name ?? path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  if (name.startsWith("@types/")) continue; // type definitions only, never bundled
  const key = `${name}@${p.version}`;
  if (seen.has(key)) continue;
  seen.add(key);
  js.push({
    name,
    dir: path,
    version: String(p.version),
    licence: licenceText(p.license),
    source: `https://www.npmjs.com/package/${name}`,
  });
}

php.sort(byNameThenVersion);
js.sort(byNameThenVersion);

// Licence files: LICENSE, LICENCE, COPYING (any case, any extension), read from the installed
// package. Identical texts are printed once, with every package that uses them.
const LICENCE_FILE = /^(licen[cs]e|copying)([.-].*)?$/i;
const texts = new Map(); // text -> [package@version, ...]
const missing = [];
for (const r of [...php, ...js]) {
  const dir = join(root, r.dir);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort() : [];
  r.licenceFile = files.length ? files.map((f) => `${r.dir}/${f}`).join(", ") : "";
  if (!files.length) missing.push(`${r.name}@${r.version}`);
  for (const f of files) {
    const text = readFileSync(join(dir, f), "utf8").replace(/\r\n?/g, "\n").trim();
    if (!texts.has(text)) texts.set(text, []);
    texts.get(text).push(`${r.name}@${r.version}`);
  }
}
const textBlocks = [...texts]
  .map(([text, users]) => ({ text, users: [...new Set(users)].sort() }))
  .sort((a, b) => a.users[0].localeCompare(b.users[0], "en"));
const missingNote = missing.length
  ? `No licence file found in the installed package for: ${missing.map((m) => `\`${m}\``).join(", ")}. Their licence is the one declared in their package metadata (listed above); see their source.`
  : "Every listed package ships a licence file.";

const table = (rows) =>
  [
    "| Package | Version | Licence | Source |",
    "|---|---|---|---|",
    ...rows.map((r) => `| \`${r.name}\` | ${r.version} | ${r.licence}${r.licenceFile ? "" : " (no licence file)"} | <${r.source}> |`),
  ].join("\n");

const summary = (rows) => {
  const counts = new Map();
  for (const r of rows) counts.set(r.licence, (counts.get(r.licence) ?? 0) + 1);
  return [...counts]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([licence, n]) => `${licence} (${n})`)
    .join(", ");
};

const out = `# Third-party licences

Generated by \`node scripts/licenses.mjs\` from \`composer.lock\` and \`package-lock.json\`. Do not edit by hand:
run the script again after any dependency change. [CREDITS.md](../CREDITS.md) has the direct dependencies with their
copyright holders, the LGPL notes and the design acknowledgements.

This list covers what a production build ships: the PHP packages \`composer install --no-dev\` installs into
\`vendor/\`, and the npm packages that can be bundled into \`public/build/\`. Development-only packages (test tools,
Vite, TypeScript, Tailwind CSS and the other build tools) and \`@types/*\` type definitions are left out.

The [full licence texts](#licence-texts) of these packages follow the lists. The same texts are written to
\`public/licenses.txt\`, which is committed and uploaded with every release, so a deployed site serves them at
\`/licenses.txt\`.

## PHP (Composer): ${php.length} packages

Licences: ${summary(php)}.

${table(php)}

## JavaScript (npm, bundled into \`public/build\`): ${js.length} packages

Licences: ${summary(js)}.

${table(js)}

## Licence texts

${missingNote}

${textBlocks
  .map((b) => `### ${b.users.length === 1 ? b.users[0] : `${b.users[0]} and ${b.users.length - 1} more`}\n\nUsed by: ${b.users.map((u) => `\`${u}\``).join(", ")}\n\n~~~~text\n${b.text}\n~~~~`)
  .join("\n\n")}
`;

const rule = "=".repeat(78);
const txt = `Third-party licences for Club Portal

These are the licence texts of the third-party packages shipped in this build:
the PHP packages in vendor/ and the JavaScript packages bundled into public/build/.
Generated by scripts/licenses.mjs; the package list with versions and sources is
docs/THIRD-PARTY-LICENSES.md in the source repository
(https://github.com/amirsubhi/clubcollection).

${missingNote.replace(/`/g, "").replace("(listed above)", "(see docs/THIRD-PARTY-LICENSES.md)")}

${textBlocks.map((b) => `${rule}\n${b.users.join("\n")}\n${rule}\n\n${b.text}\n`).join("\n")}`;

writeFileSync(join(root, "docs/THIRD-PARTY-LICENSES.md"), out);
writeFileSync(join(root, "public/licenses.txt"), txt);
console.log(
  `docs/THIRD-PARTY-LICENSES.md and public/licenses.txt: ${php.length} PHP and ${js.length} JavaScript packages, ` +
    `${textBlocks.length} distinct licence texts${missing.length ? `; no licence file: ${missing.join(", ")}` : ""}.`,
);
